// A forged world prop into the iPhone app's prop format (0226): ios/ColdGas/Resources/Props/<kind>/lod<i>.bin + props.json,
// read by ios/ColdGas/World/PropLibrary.swift's ForgeProps. Each .bin is the stage's 44-byte vertex (position, normal,
// uv, colour: float32 × 11) then uint32 indices. The colour is the palette material's base colour times the baked
// occlusion (COLOR_0); uv.x = 1 marks a retroreflector (the 'reflective' palette entry), which the world's shader lights up
// in the headlamps. Positions are in the game's frame (y up), the node transforms baked in. Deterministic: the same glb
// writes the same bytes. Build time only (the operator's Mac).
import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import { dequantize } from '@gltf-transform/functions';
import { MeshoptDecoder } from 'meshoptimizer';
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './run.mjs';

export const PROPS_DIR = join(ROOT, 'ios/ColdGas/Resources/Props');

function mul(m, x, y, z, w) {
  return [m[0] * x + m[4] * y + m[8] * z + m[12] * w, m[1] * x + m[5] * y + m[9] * z + m[13] * w, m[2] * x + m[6] * y + m[10] * z + m[14] * w];
}

/** The LODs of a packed forge glb as the app's arrays: [{ vertices: Float32Array, indices: Uint32Array }]. */
export async function nativeLods(glbPath) {
  await MeshoptDecoder.ready;
  const io = new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({ 'meshopt.decoder': MeshoptDecoder });
  const doc = await io.read(glbPath);
  await doc.transform(dequantize());
  const nodes = doc.getRoot().listNodes().filter((n) => /^LOD\d$/.test(n.getName())).sort((a, b) => a.getName().localeCompare(b.getName()));
  return nodes.map((node) => {
    const M = node.getWorldMatrix();
    // the normal matrix: the inverse transpose of the upper 3×3 (a uniform scale and a turn here, so the 3×3 renormalised)
    const v = [], idx = [];
    for (const p of node.getMesh().listPrimitives()) {
      const mat = p.getMaterial(), base = mat ? mat.getBaseColorFactor() : [0.5, 0.5, 0.5, 1];
      const glow = mat && /^reflective/.test(mat.getName()) ? 1 : 0;
      const P = p.getAttribute('POSITION'), N = p.getAttribute('NORMAL'), C = p.getAttribute('COLOR_0'), I = p.getIndices();
      const start = v.length / 11, a = [0, 0, 0], n = [0, 0, 0], c = [1, 1, 1, 1];
      for (let i = 0; i < P.getCount(); i++) {
        P.getElement(i, a); N.getElement(i, n);
        if (C) C.getElement(i, c);
        const w = mul(M, a[0], a[1], a[2], 1), nn = mul(M, n[0], n[1], n[2], 0), l = Math.hypot(...nn) || 1;
        v.push(w[0], w[1], w[2], nn[0] / l, nn[1] / l, nn[2] / l, glow, 0, base[0] * c[0], base[1] * c[1], base[2] * c[2]);
      }
      for (let i = 0; i < I.getCount(); i++) idx.push(start + I.getScalar(i));
    }
    return { vertices: Float32Array.from(v), indices: Uint32Array.from(idx) };
  });
}

/** Write a slot's LODs into the app and record them in props.json (other kinds kept). */
export async function exportNative(glbPath, slot) {
  if (!slot.native) throw new Error(`${slot.id} has no native kind`);
  const lods = await nativeLods(glbPath);
  const dir = join(PROPS_DIR, slot.native);
  mkdirSync(dir, { recursive: true });
  const list = lods.map((l, i) => {
    const file = `${slot.native}/lod${i}.bin`;
    writeFileSync(join(PROPS_DIR, file), Buffer.concat([Buffer.from(l.vertices.buffer), Buffer.from(l.indices.buffer)]));
    return { file, vertices: l.vertices.length / 11, triangles: l.indices.length / 3, end: slot.ends[i] };
  });
  const manPath = join(PROPS_DIR, 'props.json');
  const man = existsSync(manPath) ? JSON.parse(readFileSync(manPath, 'utf8')) : { kinds: {} };
  man.note = 'GENERATED by tools/forge (npm run forge -- <slot> --native). Never edit by hand.';
  man.kinds[slot.native] = list;
  man.kinds = Object.fromEntries(Object.entries(man.kinds).sort(([a], [b]) => a.localeCompare(b)));
  writeFileSync(manPath, JSON.stringify(man, null, 1) + '\n');
  return list;
}
