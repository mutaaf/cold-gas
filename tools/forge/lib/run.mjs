// Run one forge job in headless Blender and gate the result (0211). Shared by forge.mjs (archetypes) and brief.mjs
// (generated scripts). Runs on the operator's Mac: it needs Blender (BLENDER=/path/to/blender, else the usual places).
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync, copyFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gate } from './gate.mjs';
import { pack } from './pack.mjs';
import { hexLinear } from './slots.mjs';

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
const RUN_PY = join(ROOT, 'tools/forge/blender/run.py');

export function findBlender() {
  const tries = [process.env.BLENDER, '/opt/homebrew/bin/blender', '/Applications/Blender.app/Contents/MacOS/Blender', '/usr/local/bin/blender', '/usr/bin/blender'];
  for (const t of tries) if (t && existsSync(t)) return t;
  const which = spawnSync('which', ['blender'], { encoding: 'utf8' });
  if (which.status === 0 && which.stdout.trim()) return which.stdout.trim();
  return null;
}

/**
 * @param {object} o { slot, seed, out, archetype?, script?, turntable? , timeoutMs? }
 * @returns {{ report, verdict, out }}
 */
export async function forgeJob(o) {
  const blender = findBlender();
  if (!blender) throw new Error('Blender not found. The forge runs on the operator\'s Mac (set BLENDER=/path/to/blender).');
  const { slot, seed = 0 } = o;
  const out = resolve(o.out);
  mkdirSync(out, { recursive: true });
  const job = {
    id: o.id || `${slot.id}-${seed}`, slot: slot.id, kind: slot.kind, seed, out, spec: slot.spec,
    paintLinear: hexLinear(slot.paint), budgets: slot.budgets, aoReach: slot.aoReach ?? 0.7, turntable: o.turntable !== false,
    ...(o.script ? { script: resolve(o.script) } : { archetype: o.archetype || slot.archetype }),
  };
  writeFileSync(join(out, 'job.json'), JSON.stringify(job, null, 1));
  const r = spawnSync(blender, ['-b', '--factory-startup', '-noaudio', '-P', RUN_PY, '--', join(out, 'job.json')], {
    encoding: 'utf8', timeout: o.timeoutMs ?? 600_000, maxBuffer: 64 << 20,
  });
  if (r.error) throw new Error(`Blender: ${r.error.message}`);
  const reportPath = join(out, 'report.json');
  if (!existsSync(reportPath)) throw new Error(`Blender wrote no report (exit ${r.status}):\n${(r.stderr || r.stdout || '').slice(-3000)}`);
  const report = JSON.parse(readFileSync(reportPath, 'utf8'));
  const glbPath = join(out, 'model.glb');
  if (report.ok && existsSync(join(out, 'raw.glb'))) {
    const tris = await pack(join(out, 'raw.glb'), glbPath, slot.budgets);
    tris.forEach((t, i) => { if (i > 0) report[`lod${i}`] = { ...report[`lod${i}`], tris: t }; });
    writeFileSync(reportPath, JSON.stringify(report, null, 1));
  }
  const glb = existsSync(glbPath) ? new Uint8Array(readFileSync(glbPath)) : null;
  const verdict = gate(report, slot, glb);
  writeFileSync(join(out, 'gate.json'), JSON.stringify(verdict, null, 1));
  return { report, verdict, out };
}

export function printVerdict({ report, verdict, out }, label) {
  const t = verdict.facts?.tris?.join(' / ') ?? '?';
  const kb = verdict.facts?.bytes ? `${(verdict.facts.bytes / 1024).toFixed(0)} kB` : '';
  console.log(`forge: ${label}: ${verdict.ok ? 'PASS' : 'FAIL'} · ${t} tris · ${kb} · ${report.seconds ?? '?'} s · ${out}`);
  for (const f of verdict.failures) console.log(`  ✗ ${f}`);
  if (report.trace && !report.ok) console.log(report.trace);
}

// Promote a gated asset into the game: public/forge/<slot>.glb, its turntable beside the docs, the manifest.
export function promote({ out, verdict, report }, slot, extra = {}) {
  if (!verdict.ok) throw new Error('only an asset that passed the gate can be promoted');
  const pub = join(ROOT, 'public/forge');
  const docs = join(ROOT, 'docs/forge');
  mkdirSync(pub, { recursive: true });
  mkdirSync(docs, { recursive: true });
  copyFileSync(join(out, 'model.glb'), join(pub, `${slot.id}.glb`));
  if (existsSync(join(out, 'turntable.png'))) copyFileSync(join(out, 'turntable.png'), join(docs, `${slot.id}.png`));
  const manPath = join(ROOT, 'src/render/forge-manifest.json');
  const man = existsSync(manPath) ? JSON.parse(readFileSync(manPath, 'utf8')) : { note: '', assets: {} };
  man.note = 'GENERATED by tools/forge (npm run forge -- <slot> --promote). Never edit by hand.';
  man.assets[slot.id] = {
    file: `forge/${slot.id}.glb`, kind: slot.kind, bytes: verdict.facts.bytes, tris: verdict.facts.tris,
    seed: report.seed, source: report.source, ...extra,
  };
  man.assets = Object.fromEntries(Object.entries(man.assets).sort(([a], [b]) => a.localeCompare(b)));
  writeFileSync(manPath, JSON.stringify(man, null, 1) + '\n');
  return manPath;
}
