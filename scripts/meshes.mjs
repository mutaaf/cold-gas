#!/usr/bin/env node
// The native app's meshes, from the web's own procedural generators (docs/NATIVE.md §4, 0148): one source
// for the car. Runs src/render/roadster.js's makeRoadster() in Node, bakes every mesh into the car's ground
// frame (y = 0 at the contact patch, +x the car's LEFT, +z forward), merges by material, and writes
//   ios/ColdGas/Resources/Meshes/roadster.bin   float32 position(3) normal(3) per vertex, then uint32 indices
//   ios/ColdGas/Resources/Meshes/roadster.json  submeshes: material, PBR numbers, vertex/index ranges
// GENERATED: never hand-edit. `node scripts/meshes.mjs --check` exits 1 if the files are stale.
// The plate's canvas texture is stubbed (Node has no canvas): it exports as its base colour.
import { writeFileSync, readFileSync, mkdirSync, existsSync } from 'node:fs';
import * as THREE from 'three';

globalThis.document ??= { createElement: () => ({ width: 0, height: 0, getContext: () => new Proxy({}, { get: () => () => {}, set: () => true }) }) };
const { makeRoadster } = await import('../src/render/roadster.js');

const OUT = 'ios/ColdGas/Resources/Meshes';
const check = process.argv.includes('--check');

function exportObject(root, name) {
  root.updateMatrixWorld(true);
  const groups = new Map();   // material uuid → { mat, pos: [], nrm: [], idx: [] }
  const m4 = new THREE.Matrix4(), n3 = new THREE.Matrix3(), v = new THREE.Vector3(), n = new THREE.Vector3();
  root.traverse((o) => {
    if (!(o.isMesh || o.isInstancedMesh) || !o.visible) return;
    const mats = Array.isArray(o.material) ? o.material : [o.material];
    const g = o.geometry;   // indexed or not: idxAt() reads either
    const P = g.attributes.position, N = g.attributes.normal;
    if (!N) g.computeVertexNormals();
    const count = o.isInstancedMesh ? o.count : 1;
    for (let inst = 0; inst < count; inst++) {
      m4.copy(o.matrixWorld);
      if (o.isInstancedMesh) { const mi = new THREE.Matrix4(); o.getMatrixAt(inst, mi); m4.multiply(mi); }
      n3.getNormalMatrix(m4);
      const flip = m4.determinant() < 0;
      const ranges = g.groups.length ? g.groups : [{ start: 0, count: g.index ? g.index.count : P.count, materialIndex: 0 }];
      for (const r of ranges) {
        const mat = mats[r.materialIndex ?? 0];
        if (!mat || mat.visible === false) continue;
        if (!groups.has(mat.uuid)) groups.set(mat.uuid, { mat, pos: [], nrm: [], idx: [] });
        const gr = groups.get(mat.uuid), base = gr.pos.length / 3, remap = new Map();
        const idxAt = (k) => (g.index ? g.index.getX(k) : k);
        for (let k = r.start; k < r.start + r.count; k += 3) {
          const tri = [idxAt(k), idxAt(k + 1), idxAt(k + 2)];
          if (flip) [tri[1], tri[2]] = [tri[2], tri[1]];
          for (const i of tri) {
            if (!remap.has(i)) {
              remap.set(i, base + remap.size);
              v.fromBufferAttribute(P, i).applyMatrix4(m4);
              n.fromBufferAttribute(g.attributes.normal, i).applyMatrix3(n3).normalize();
              gr.pos.push(v.x, v.y, v.z); gr.nrm.push(n.x, n.y, n.z);
            }
            gr.idx.push(remap.get(i));
          }
        }
      }
    }
  });
  // Deterministic order: by material name/type, then colour.
  const list = [...groups.values()].sort((a, b) => key(a.mat).localeCompare(key(b.mat)));
  let verts = 0, idxs = 0;
  const sub = [], vbuf = [], ibuf = [];
  for (const gr of list) {
    const m = gr.mat, nv = gr.pos.length / 3;
    sub.push({
      material: key(m), kind: m.type, color: '#' + (m.color?.getHexString() ?? 'ffffff'),
      emissive: m.type === 'MeshBasicMaterial', opacity: m.transparent ? m.opacity : 1,
      doubleSided: m.side === THREE.DoubleSide,
      metalness: m.metalness ?? 0, roughness: m.roughness ?? 1, clearcoat: m.clearcoat ?? 0, clearcoatRoughness: m.clearcoatRoughness ?? 0,
      vertexStart: verts, vertexCount: nv, indexStart: idxs, indexCount: gr.idx.length,
    });
    for (let i = 0; i < nv; i++) vbuf.push(gr.pos[3 * i], gr.pos[3 * i + 1], gr.pos[3 * i + 2], gr.nrm[3 * i], gr.nrm[3 * i + 1], gr.nrm[3 * i + 2]);
    for (const i of gr.idx) ibuf.push(i);   // already 0-based within this submesh
    verts += nv; idxs += gr.idx.length;
  }
  // Indices are per submesh (0-based within it): the renderer draws each with its own vertex offset.
  const vb = Buffer.from(new Float32Array(vbuf).buffer), ib = Buffer.from(new Uint32Array(ibuf).buffer);
  const bounds = new THREE.Box3().setFromObject(root);
  const manifest = {
    note: 'GENERATED by scripts/meshes.mjs from src/render/roadster.js. Never edit by hand.',
    name, frame: 'ground: y = 0 at the contact patch, +x the car LEFT, +z forward (metres)',
    vertexStride: 24, vertexCount: verts, indexCount: idxs, indexOffsetBytes: vb.length,
    bounds: { min: bounds.min.toArray().map(r4), max: bounds.max.toArray().map(r4) }, submeshes: sub,
  };
  return { bin: Buffer.concat([vb, ib]), json: JSON.stringify(manifest, null, 1) + '\n' };
}
const r4 = (x) => Math.round(x * 1e4) / 1e4;
const key = (m) => `${m.name || m.type}-${m.color?.getHexString() ?? ''}-${m.type}`;

const car = makeRoadster();
const root = car.root ?? car.group ?? car;
const out = exportObject(root.isObject3D ? root : car.object, 'roadster');
if (check) {
  const ok = existsSync(`${OUT}/roadster.json`) && readFileSync(`${OUT}/roadster.json`, 'utf8') === out.json && readFileSync(`${OUT}/roadster.bin`).equals(out.bin);
  if (!ok) { console.error('meshes: stale. Run `node scripts/meshes.mjs` and commit (docs/NATIVE.md §4).'); process.exit(1); }
  console.log('meshes: current');
} else {
  mkdirSync(OUT, { recursive: true });
  writeFileSync(`${OUT}/roadster.bin`, out.bin); writeFileSync(`${OUT}/roadster.json`, out.json);
  const m = JSON.parse(out.json);
  console.log(`meshes: roadster ${m.vertexCount} vertices, ${m.indexCount / 3} triangles, ${m.submeshes.length} materials, ${(out.bin.length / 1e6).toFixed(2)} MB`);
}
