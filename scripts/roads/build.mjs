// Build the Free Drive roads from open data (build time only; the game never calls these hosts).
//
//   node scripts/roads/build.mjs            all roads
//   node scripts/roads/build.mjs stelvio    one road
//
// For each road in roads.config.mjs:
//   1. OpenStreetMap (Overpass API): the ways carrying the road's ref, guard rails and walls,
//      woods and forests, lakes. The route is the shortest path over the road's ways between
//      the two endpoints.
//   2. A centripetal Catmull-Rom spline through the OSM nodes, resampled every 3 m, then lightly
//      relaxed (OSM hairpins are often three nodes).
//   3. Elevation from the AWS Terrain Tiles (Terrarium PNGs, zoom 13 ≈ 10–15 m) along the
//      centreline, bridges and tunnels spanned straight between their ends, then smoothed
//      (σ ≈ 24 m) the way a road is graded.
//   4. Width from OSM `width`/`lanes`, widened through tight hairpins the way design manuals
//      widen them for long vehicles (n·L²/2R). Banking from curvature and the posted speed
//      (superelevation up to 6 %).
//   5. Barriers: tagged OSM guard rails and walls near the edge, every bridge (parapets) and
//      tunnel (walls), and wherever the ground drops more than 5 m within 8 m of the edge.
//   6. Terrain: a near heightfield (15 m) around the road and a far one (120 m, ±18 km) for the
//      skyline, Uint16 decimetres, row-delta coded so gzip can squeeze them. A tree-cover mask
//      (30 m) rasterised from OSM woods/forests.
// Output: public/roads/<id>.bin.gz (one gzip of a small binary; layout in src/sim/roads.js) and
// src/drive/manifest.js (what the road picker shows, without loading any road).
import { writeFileSync, mkdirSync } from 'node:fs';
import { gzipSync } from 'node:zlib';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { overpass, elevation } from './fetch.mjs';
import { ROADS, DEM_CREDIT, OSM_CREDIT } from './roads.config.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = join(ROOT, 'public', 'roads');
mkdirSync(OUT, { recursive: true });

const R_EARTH = 6371008.8, D2R = Math.PI / 180;
const SPACING = 3;              // m between road samples
const NEAR_CELL = 15, NEAR_MARGIN = 1500;
const FAR_CELL = 120, FAR_HALF = 18000;
const TREE_CELL = 30;
const Z_NEAR = 13, Z_FAR = 10;

function writeManifest(list) {
  const src = `// GENERATED by scripts/roads/build.mjs — do not edit. What the Free Drive picker shows for each
// road (the road itself is public/roads/<id>.bin.gz, fetched only when it is chosen).
export const OSM_CREDIT = ${JSON.stringify(OSM_CREDIT)};
export const ROADS = ${JSON.stringify(list, null, 1)};
`;
  writeFileSync(join(ROOT, 'src', 'drive', 'manifest.js'), src);
}

async function buildRoad(road) {
  const [s, w, n, e] = road.bbox;
  const bb = `(${s},${w},${n},${e})`;
  const osm = await overpass(`[out:json][timeout:120];${road.ways}${bb};out body geom;`);
  const ways = osm.elements.filter((x) => x.type === 'way' && x.geometry);
  const path = route(ways, road.from, road.to);
  console.log(`  route: ${path.length} OSM nodes`);

  // Local tangent plane at the route's centre: x east, z south (right-handed with y up).
  let la0 = Infinity, la1 = -Infinity, lo0 = Infinity, lo1 = -Infinity;
  for (const p of path) { la0 = Math.min(la0, p.lat); la1 = Math.max(la1, p.lat); lo0 = Math.min(lo0, p.lon); lo1 = Math.max(lo1, p.lon); }
  const lat0 = (la0 + la1) / 2, lon0 = (lo0 + lo1) / 2, kx = Math.cos(lat0 * D2R) * R_EARTH * D2R, kz = R_EARTH * D2R;
  const toXZ = (lat, lon) => [(lon - lon0) * kx, -(lat - lat0) * kz];
  const toLL = (x, z) => [lat0 - z / kz, lon0 + x / kx];

  // --- Centreline ---------------------------------------------------------------------------------
  const pts = [];
  for (const p of path) {
    const [x, z] = toXZ(p.lat, p.lon);
    const last = pts[pts.length - 1];
    if (last && Math.hypot(x - last.x, z - last.z) < 0.5) continue;
    pts.push({ x, z, tags: p.tags });
  }
  let S = resample(pts, SPACING);
  for (let it = 0; it < 6; it++) relax(S);
  // Kinks: where OSM draws a hairpin's apex as one sharp node the spline keeps a corner (>23°
  // between consecutive 3 m segments). Ease just those few points; the hairpins keep their size.
  for (let pass = 0; pass < 8; pass++) {
    let kinks = 0;
    for (let i = 1; i < S.length - 1; i++) {
      const a = S[i - 1], b = S[i], c = S[i + 1];
      const ux = b.x - a.x, uz = b.z - a.z, vx = c.x - b.x, vz = c.z - b.z;
      if (Math.abs(Math.atan2(ux * vz - uz * vx, ux * vx + uz * vz)) < 0.4) continue;
      kinks++;
      for (const k of [i - 1, i, i + 1]) {
        if (k < 1 || k > S.length - 2) continue;
        S[k].x += ((S[k - 1].x + S[k + 1].x) / 2 - S[k].x) * 0.35; S[k].z += ((S[k - 1].z + S[k + 1].z) / 2 - S[k].z) * 0.35;
      }
    }
    const r = resample(S, SPACING); S.length = 0; S.push(...r);
    if (!kinks) break;
  }
  const N = S.length;
  const length = (N - 1) * SPACING;
  console.log(`  ${N} samples, ${(length / 1000).toFixed(2)} km`);

  // Tags per sample.
  const bridge = S.map((p) => (p.tags.bridge && p.tags.bridge !== 'no' ? 1 : 0));
  const tunnel = S.map((p) => (p.tags.tunnel && p.tags.tunnel !== 'no' ? 1 : 0));

  // --- Elevation --------------------------------------------------------------------------------
  const yRaw = new Float64Array(N);
  for (let i = 0; i < N; i++) { const [la, lo] = toLL(S[i].x, S[i].z); yRaw[i] = await elevation(la, lo, Z_NEAR); }
  const y = Float64Array.from(yRaw);
  // Bridges and tunnels: straight between their ends (a bridge doesn't follow the canyon).
  for (const span of runs(bridge.map((b, i) => b || tunnel[i]))) {
    const a = Math.max(0, span[0] - 3), b = Math.min(N - 1, span[1] + 3);
    const ya = avg(yRaw, Math.max(0, a - 4), a), yb = avg(yRaw, b, Math.min(N - 1, b + 4));
    for (let i = a; i <= b; i++) y[i] = ya + ((yb - ya) * (i - a)) / Math.max(1, b - a);
  }
  // Coastal roads never dip below the sea (DEM noise at the shoreline).
  if (road.coast) for (let i = 0; i < N; i++) y[i] = Math.max(y[i], 2.5);
  // On stacked switchbacks the DEM under the centreline mixes in the slope between the legs, so a
  // running median (±30 m) takes out the spikes, a Gaussian (σ ≈ 30 m) the noise, and the grade
  // is held to the road's design maximum the way it was built (forward and backward passes).
  let ys = median(y, 10);
  ys = gauss(gauss(ys, 10), 10);
  // Hairpins are built flatter: the inside lane of a 10 m bend is a fraction of the centreline's
  // length, so the grade is eased where the road turns tightly (limit ∝ (R − ¾·w)/R).
  const lim = new Float64Array(N);
  for (let i = 0; i < N; i++) {
    const a = Math.max(0, i - 3), b = Math.min(N - 1, i + 3);
    const ax = S[Math.min(N - 1, a + 1)].x - S[a].x, az = S[Math.min(N - 1, a + 1)].z - S[a].z, bx = S[b].x - S[Math.max(0, b - 1)].x, bz = S[b].z - S[Math.max(0, b - 1)].z;
    const turn = Math.abs(Math.atan2(ax * bz - az * bx, ax * bx + az * bz));
    const R = turn > 1e-4 ? ((b - a) * SPACING) / turn : 1e5;
    lim[i] = road.maxGrade * SPACING * Math.max(0.3, Math.min(1, (R - 0.75 * 6.5) / R));
  }
  ys = gradeLimit(ys, gauss(lim, 3));
  ys = gauss(ys, 4);
  // Keep a bridge's deck straight after the smoothing too.
  for (const span of runs(bridge)) {
    const a = span[0], b = span[1];
    for (let i = a; i <= b; i++) ys[i] = ys[a] + ((ys[b] - ys[a]) * (i - a)) / Math.max(1, b - a);
  }

  // Bridges over navigable water rise to their charted clearance (OSM seamark:bridge:clearance_height):
  // a sin² hump over the span and 45 m of approach either side, zero grade at both ends.
  for (const span of runs(bridge)) {
    let c = 0;
    for (let i = span[0]; i <= span[1]; i++) c = Math.max(c, parseFloat(S[i].tags['seamark:bridge:clearance_height']) || 0);
    if (!c) continue;
    const a = Math.max(0, span[0] - 15), b = Math.min(N - 1, span[1] + 15), mid = (a + b) >> 1;
    const rise = c + 1.6 - ys[mid];
    if (rise <= 0) continue;
    for (let i = a; i <= b; i++) ys[i] += rise * Math.sin((Math.PI * (i - a)) / (b - a)) ** 2;
    console.log(`  bridge hump: ${c} m clearance, +${rise.toFixed(1)} m over ${((b - a) * SPACING).toFixed(0)} m`);
  }

  // --- Heading, curvature, width, banking --------------------------------------------------------
  const tx = new Float64Array(N), tz = new Float64Array(N), kappa = new Float64Array(N);
  for (let i = 0; i < N; i++) {
    const a = S[Math.max(0, i - 1)], b = S[Math.min(N - 1, i + 1)];
    const l = Math.hypot(b.x - a.x, b.z - a.z) || 1; tx[i] = (b.x - a.x) / l; tz[i] = (b.z - a.z) / l;
  }
  for (let i = 0; i < N; i++) {
    const a = Math.max(0, i - 3), b = Math.min(N - 1, i + 3);
    // Signed curvature, + to the left (left = (tz, −tx) in this x-east/z-south frame).
    const cross = tx[a] * tz[b] - tz[a] * tx[b];
    const dot = tx[a] * tx[b] + tz[a] * tz[b];
    kappa[i] = -Math.atan2(cross, dot) / ((b - a) * SPACING);
  }
  const kap = gauss(kappa, 3);
  const halfW = new Float64Array(N);
  for (let i = 0; i < N; i++) {
    const t = S[i].tags;
    let w = parseFloat(t.width);
    if (!(w > 3 && w < 30)) w = (parseInt(t.lanes, 10) || 2) * (road.marking === 'us' ? 3.5 : 3.0) + 0.4;
    if (t.oneway === 'yes' && !t.lanes) w = Math.max(w, 4.5);
    halfW[i] = w / 2;
  }
  let hw = gauss(halfW, 6);
  // Hairpin widening (two lanes, a 6 m design vehicle): n·L²/(2R), up to 3 m.
  hw = hw.map((h, i) => { const R = 1 / Math.max(1e-4, Math.abs(kap[i])); return h + (R < 60 ? Math.min(3, (2 * 36) / (2 * R)) / 2 : 0); });
  hw = gauss(hw, 4);
  const v = road.speed / 3.6;
  let bank = new Float64Array(N);
  for (let i = 0; i < N; i++) {
    const e = Math.min(0.06, (v * v * Math.abs(kap[i])) / 9.81 * 0.45);
    bank[i] = e < 0.012 ? 0 : -Math.sign(kap[i]) * e;      // inside edge lower
  }
  bank = gauss(bank, 6);

  // --- Terrain -----------------------------------------------------------------------------------
  let minX = Infinity, maxX = -Infinity, minZ = Infinity, maxZ = -Infinity;
  for (const p of S) { minX = Math.min(minX, p.x); maxX = Math.max(maxX, p.x); minZ = Math.min(minZ, p.z); maxZ = Math.max(maxZ, p.z); }
  const near = await grid(minX - NEAR_MARGIN, minZ - NEAR_MARGIN, maxX + NEAR_MARGIN, maxZ + NEAR_MARGIN, NEAR_CELL, Z_NEAR, toLL, road.coast);
  const far = await grid(-FAR_HALF, -FAR_HALF, FAR_HALF, FAR_HALF, FAR_CELL, Z_FAR, toLL, road.coast);
  console.log(`  near grid ${near.nx}×${near.nz}, far ${far.nx}×${far.nz}`);
  const demAt = (x, z) => sampleGrid(near, x, z);

  // --- Barriers ----------------------------------------------------------------------------------
  // 0 none · 1 steel guard rail · 2 stone/concrete wall · 3 tunnel wall
  const railL = new Uint8Array(N), railR = new Uint8Array(N);
  const styleDefault = road.rail === 'stone' ? 2 : 1;
  for (let i = 0; i < N; i++) {
    if (tunnel[i]) { railL[i] = 3; railR[i] = 3; continue; }
    if (bridge[i]) { railL[i] = 2; railR[i] = 2; continue; }
    const lx = tz[i], lz = -tx[i];
    for (const [side, arr] of [[1, railL], [-1, railR]]) {
      const d = hw[i] + 8;
      const g = demAt(S[i].x + lx * d * side, S[i].z + lz * d * side);
      if (g < ys[i] - 5) arr[i] = styleDefault;
    }
  }
  const bar = await overpass(`[out:json][timeout:120];way["barrier"~"^(guard_rail|wall|retaining_wall|jersey_barrier)$"](${toLL(minX - 50, maxZ + 50)[0]},${toLL(minX - 50, 0)[1]},${toLL(0, minZ - 50)[0]},${toLL(maxX + 50, 0)[1]});out body geom;`);
  const index = segIndex(S);
  let tagged = 0;
  for (const wy of bar.elements.filter((x) => x.type === 'way' && x.geometry)) {
    const style = wy.tags.barrier === 'guard_rail' ? 1 : 2;
    const g = wy.geometry.map((p) => toXZ(p.lat, p.lon));
    for (let k = 0; k + 1 < g.length; k++) {
      const L = Math.hypot(g[k + 1][0] - g[k][0], g[k + 1][1] - g[k][1]);
      for (let t = 0; t <= L; t += 2) {
        const x = g[k][0] + ((g[k + 1][0] - g[k][0]) * t) / (L || 1), z = g[k][1] + ((g[k + 1][1] - g[k][1]) * t) / (L || 1);
        const i = index(x, z);
        if (i < 0 || tunnel[i] || bridge[i]) continue;
        const dx = x - S[i].x, dz = z - S[i].z, lat = dx * tz[i] - dz * tx[i];
        if (Math.abs(lat) < hw[i] - 1 || Math.abs(lat) > hw[i] + 6) continue;
        const arr = lat > 0 ? railL : railR;
        for (let j = Math.max(0, i - 1); j <= Math.min(N - 1, i + 1); j++) arr[j] = style;
        tagged++;
      }
    }
  }
  console.log(`  ${bar.elements.length} OSM barriers (${tagged} samples tagged)`);
  for (const arr of [railL, railR]) cleanRuns(arr, 5, 4);

  // --- Trees and lakes ---------------------------------------------------------------------------
  const llS = toLL(0, near.z0 + near.nz * near.cell)[0], llN = toLL(0, near.z0)[0], llW = toLL(near.x0, 0)[1], llE = toLL(near.x0 + near.nx * near.cell, 0)[1];
  const nb = `(${llS},${llW},${llN},${llE})`;
  const woods = await overpass(`[out:json][timeout:180];(way["natural"="wood"]${nb};way["landuse"="forest"]${nb};relation["natural"="wood"]${nb};relation["landuse"="forest"]${nb};);out body geom;`);
  const trees = treeMask(woods, near, toXZ);
  const waters = await overpass(`[out:json][timeout:180];(way["natural"="water"]${nb};relation["natural"="water"]${nb};);out body geom;`);
  const lakes = lakeShapes(waters, toXZ, demAt, near);
  console.log(`  trees ${trees.cover.toFixed(1)}% cover, ${lakes.length} lakes`);

  // --- Pack --------------------------------------------------------------------------------------
  const flags = new Uint8Array(N);
  for (let i = 0; i < N; i++) flags[i] = bridge[i] | (tunnel[i] << 1) | (railL[i] << 2) | (railR[i] << 4);
  const name = S.map((p) => p.tags.name || '');
  const meta = {
    v: 1, id: road.id, n: N, spacing: SPACING, origin: { lat: lat0, lon: lon0 },
    coast: road.coast, marking: road.marking, speed: road.speed, sun: road.sun,
    near: gridMeta(near), far: gridMeta(far), trees: { x0: trees.x0, z0: trees.z0, cell: TREE_CELL, nx: trees.nx, nz: trees.nz },
    lakes, names: nameRuns(name), pano: await panorama(ys, toLL),
  };
  const parts = [];
  const f32 = (arr) => parts.push(Buffer.from(Float32Array.from(arr).buffer));
  f32(S.map((p) => p.x)); f32(S.map((p) => p.z)); f32(ys);
  parts.push(Buffer.from(Uint8Array.from(hw, (h) => Math.max(0, Math.min(255, Math.round(h / 0.05)))).buffer));
  parts.push(Buffer.from(Int8Array.from(bank, (b) => Math.max(-127, Math.min(127, Math.round(b * 1000)))).buffer));
  parts.push(Buffer.from(flags.buffer));
  pad4(parts);
  parts.push(Buffer.from(deltaU16(near).buffer)); pad4(parts);
  parts.push(Buffer.from(deltaU16(far).buffer)); pad4(parts);
  parts.push(Buffer.from(trees.data.buffer)); pad4(parts);
  const json = Buffer.from(JSON.stringify(meta));
  const head = Buffer.alloc(8);
  head.write('CGR1', 0, 'ascii'); head.writeUInt32LE(json.length, 4);
  const all = [head, json]; pad4(all);
  const raw = Buffer.concat([...all, ...parts]);
  const gz = gzipSync(raw, { level: 9 });
  writeFileSync(join(OUT, `${road.id}.bin.gz`), gz);
  console.log(`  wrote ${road.id}.bin.gz: ${(raw.length / 1024).toFixed(0)} KB raw, ${(gz.length / 1024).toFixed(0)} KB gzip`);

  // --- Picker card -------------------------------------------------------------------------------
  let gain = 0, loss = 0;
  for (let i = 1; i < N; i++) { const d = ys[i] - ys[i - 1]; if (d > 0) gain += d; else loss -= d; }
  let maxGrade = 0;
  for (let i = 10; i < N - 10; i += 5) maxGrade = Math.max(maxGrade, Math.abs(ys[i + 10] - ys[i - 10]) / (20 * SPACING));
  let hairpins = 0;
  for (let i = 0, last = -1e9; i < N; i++) {
    // A hairpin: the heading turns ≥ 150° within 60 m.
    const j = Math.min(N - 1, i + 20);
    const turn = Math.acos(Math.max(-1, Math.min(1, tx[i] * tx[j] + tz[i] * tz[j])));
    if (turn > 150 * D2R && i - last > 30) { hairpins++; last = i; }
  }
  const step = Math.max(1, Math.floor(N / 90));
  const sil = [];
  const span = Math.max(maxX - minX, maxZ - minZ);
  for (let i = 0; i < N; i += step) sil.push(+((S[i].x - minX) / span).toFixed(3), +((S[i].z - minZ) / span).toFixed(3));
  sil.push(+((S[N - 1].x - minX) / span).toFixed(3), +((S[N - 1].z - minZ) / span).toFixed(3));
  const prof = [];
  for (let k = 0; k <= 48; k++) prof.push(Math.round(ys[Math.round((k / 48) * (N - 1))]));
  return {
    id: road.id, name: road.name, local: road.local, country: road.country, blurb: road.blurb,
    lengthKm: +(length / 1000).toFixed(1), startEle: Math.round(ys[0]), endEle: Math.round(ys[N - 1]),
    maxEle: Math.round(Math.max(...ys)), minEle: Math.round(Math.min(...ys)), gain: Math.round(gain), loss: Math.round(loss),
    maxGradePct: +(maxGrade * 100).toFixed(1), hairpins, bytes: gz.length,
    silhouette: sil, aspect: +((maxZ - minZ) / span).toFixed(3), aspectX: +((maxX - minX) / span).toFixed(3), profile: prof,
    credit: { osm: OSM_CREDIT, dem: DEM_CREDIT[road.dem] }, sun: road.sun, coast: road.coast,
  };
}

// --- Route: shortest path over the road's ways (Dijkstra) ----------------------------------------
function route(ways, from, to) {
  const nodes = new Map(), adj = new Map();
  for (const w of ways) {
    for (let i = 0; i < w.nodes.length; i++) {
      nodes.set(w.nodes[i], { lat: w.geometry[i].lat, lon: w.geometry[i].lon });
      if (i) {
        const a = w.nodes[i - 1], b = w.nodes[i];
        const d = hav(w.geometry[i - 1], w.geometry[i]);
        (adj.get(a) || adj.set(a, []).get(a)).push([b, d, w.tags]);
        (adj.get(b) || adj.set(b, []).get(b)).push([a, d, w.tags]);
      }
    }
  }
  const nearest = ([lat, lon]) => { let best = null, bd = Infinity; for (const [id, p] of nodes) { const d = hav(p, { lat, lon }); if (d < bd && adj.has(id)) { bd = d; best = id; } } return best; };
  const A = nearest(from), B = nearest(to);
  const dist = new Map([[A, 0]]), prev = new Map(), done = new Set();
  const open = [[0, A]];
  while (open.length) {
    open.sort((p, q) => p[0] - q[0]);
    const [d, u] = open.shift();
    if (done.has(u)) continue;
    done.add(u);
    if (u === B) break;
    for (const [v, w, tags] of adj.get(u) || []) {
      const nd = d + w;
      if (nd < (dist.get(v) ?? Infinity)) { dist.set(v, nd); prev.set(v, [u, tags]); open.push([nd, v]); }
    }
  }
  if (!prev.has(B)) throw new Error('no route between the endpoints');
  const out = [];
  let u = B, tags = prev.get(B)[1];
  while (u !== undefined) {
    const p = nodes.get(u);
    out.push({ lat: p.lat, lon: p.lon, tags });
    const pr = prev.get(u);
    if (!pr) break;
    tags = pr[1]; u = pr[0];
  }
  return out.reverse();
}
function hav(a, b) {
  const dLat = (b.lat - a.lat) * D2R, dLon = (b.lon - a.lon) * D2R;
  const s = Math.sin(dLat / 2) ** 2 + Math.cos(a.lat * D2R) * Math.cos(b.lat * D2R) * Math.sin(dLon / 2) ** 2;
  return 2 * R_EARTH * Math.asin(Math.sqrt(s));
}

// Centripetal Catmull-Rom through the points, resampled at `step` metres.
function resample(pts, step) {
  const dense = [];
  const P = (i) => pts[Math.max(0, Math.min(pts.length - 1, i))];
  for (let i = 0; i < pts.length - 1; i++) {
    const p0 = P(i - 1), p1 = P(i), p2 = P(i + 1), p3 = P(i + 2);
    const segLen = Math.hypot(p2.x - p1.x, p2.z - p1.z);
    const n = Math.max(1, Math.ceil(segLen / 0.5));
    for (let k = 0; k < n; k++) {
      const [x, z] = catmull(p0, p1, p2, p3, k / n);
      dense.push({ x, z, tags: p1.tags });
    }
  }
  dense.push({ x: pts.at(-1).x, z: pts.at(-1).z, tags: pts.at(-2).tags });
  const out = [{ ...dense[0] }];
  let acc = 0, target = step;
  for (let i = 1; i < dense.length; i++) {
    const a = dense[i - 1], b = dense[i];
    const L = Math.hypot(b.x - a.x, b.z - a.z);
    while (acc + L >= target) {
      const t = (target - acc) / L;
      out.push({ x: a.x + (b.x - a.x) * t, z: a.z + (b.z - a.z) * t, tags: a.tags });
      target += step;
    }
    acc += L;
  }
  return out;
}
function catmull(p0, p1, p2, p3, t) {
  const al = 0.5;
  const tj = (a, b) => Math.max(1e-4, Math.hypot(b.x - a.x, b.z - a.z) ** al);
  const t0 = 0, t1 = t0 + tj(p0, p1), t2 = t1 + tj(p1, p2), t3 = t2 + tj(p2, p3);
  const u = t1 + (t2 - t1) * t;
  const L = (a, b, ta, tb) => [((tb - u) * a[0] + (u - ta) * b[0]) / (tb - ta), ((tb - u) * a[1] + (u - ta) * b[1]) / (tb - ta)];
  const P0 = [p0.x, p0.z], P1 = [p1.x, p1.z], P2 = [p2.x, p2.z], P3 = [p3.x, p3.z];
  const A1 = L(P0, P1, t0, t1), A2 = L(P1, P2, t1, t2), A3 = L(P2, P3, t2, t3);
  const B1 = L(A1, A2, t0, t2), B2 = L(A2, A3, t1, t3);
  return L(B1, B2, t1, t2);
}
// One Laplacian pass, then re-space evenly (keeps 3 m between samples).
function relax(S) {
  const xs = S.map((p) => p.x), zs = S.map((p) => p.z);
  for (let i = 1; i < S.length - 1; i++) { S[i].x = 0.5 * xs[i] + 0.25 * (xs[i - 1] + xs[i + 1]); S[i].z = 0.5 * zs[i] + 0.25 * (zs[i - 1] + zs[i + 1]); }
  const r = resample(S, SPACING);
  S.length = 0; S.push(...r);
}

function median(a, r) {
  const out = new Float64Array(a.length), w = [];
  for (let i = 0; i < a.length; i++) {
    w.length = 0;
    for (let k = Math.max(0, i - r); k <= Math.min(a.length - 1, i + r); k++) w.push(a[k]);
    w.sort((p, q) => p - q);
    out[i] = w[w.length >> 1];
  }
  return out;
}
// Hold |Δy| per sample to `dmax`: clamp forward and backward, average, repeat.
function gradeLimit(a, dm) {
  let y = Float64Array.from(a);
  const lim = (i) => (typeof dm === 'number' ? dm : dm[i]);
  for (let it = 0; it < 8; it++) {
    const f = Float64Array.from(y), b = Float64Array.from(y);
    for (let i = 1; i < y.length; i++) f[i] = Math.max(f[i - 1] - lim(i), Math.min(f[i - 1] + lim(i), f[i]));
    for (let i = y.length - 2; i >= 0; i--) b[i] = Math.max(b[i + 1] - lim(i), Math.min(b[i + 1] + lim(i), b[i]));
    for (let i = 0; i < y.length; i++) y[i] = (f[i] + b[i]) / 2;
  }
  return y;
}
const avg = (a, i0, i1) => { let s = 0; for (let i = i0; i <= i1; i++) s += a[i]; return s / (i1 - i0 + 1); };
function gauss(a, sigma) {
  const r = Math.ceil(sigma * 3), w = [];
  for (let k = -r; k <= r; k++) w.push(Math.exp(-(k * k) / (2 * sigma * sigma)));
  const out = new Float64Array(a.length);
  for (let i = 0; i < a.length; i++) {
    let s = 0, ws = 0;
    for (let k = -r; k <= r; k++) { const j = i + k; if (j < 0 || j >= a.length) continue; s += a[j] * w[k + r]; ws += w[k + r]; }
    out[i] = s / ws;
  }
  return out;
}
function runs(flags) {
  const out = [];
  for (let i = 0; i < flags.length; i++) {
    if (!flags[i]) continue;
    let j = i; while (j + 1 < flags.length && flags[j + 1]) j++;
    out.push([i, j]); i = j;
  }
  return out;
}
// Close gaps shorter than `gap` samples (same style either side) and drop runs shorter than `min`.
function cleanRuns(arr, gap, min) {
  for (let i = 1; i < arr.length; i++) {
    if (arr[i] || !arr[i - 1]) continue;
    let j = i; while (j < arr.length && !arr[j]) j++;
    if (j < arr.length && j - i <= gap && arr[j] === arr[i - 1]) for (let k = i; k < j; k++) arr[k] = arr[i - 1];
    i = j;
  }
  for (const [a, b] of runs(arr)) if (b - a + 1 < min) for (let k = a; k <= b; k++) arr[k] = 0;
}

async function grid(x0, z0, x1, z1, cell, zoom, toLL, coast) {
  const nx = Math.ceil((x1 - x0) / cell) + 1, nz = Math.ceil((z1 - z0) / cell) + 1;
  const h = new Float32Array(nx * nz);
  for (let j = 0; j < nz; j++) for (let i = 0; i < nx; i++) {
    const [la, lo] = toLL(x0 + i * cell, z0 + j * cell);
    let v = await elevation(la, lo, zoom);
    // Offshore, the fine US/Norwegian sources stop at the waterline (0 or a void fill ≈1 m); the
    // coarse zoom carries the bathymetry, so the sea floor comes from there.
    if (coast && zoom >= 12 && v < 1.5) { const deep = await elevation(la, lo, 10); v = Math.min(v, deep * 0.6 - 1.5, -2.5); }
    if (coast) v = Math.max(v, -60);
    h[j * nx + i] = v;
  }
  let lo = Infinity; for (const v of h) lo = Math.min(lo, v);
  return { x0, z0, cell, nx, nz, h, base: Math.floor(lo) };
}
const gridMeta = (g) => ({ x0: g.x0, z0: g.z0, cell: g.cell, nx: g.nx, nz: g.nz, base: g.base, scale: 0.1 });
function sampleGrid(g, x, z) {
  const fx = Math.max(0, Math.min(g.nx - 1.001, (x - g.x0) / g.cell)), fz = Math.max(0, Math.min(g.nz - 1.001, (z - g.z0) / g.cell));
  const i = Math.floor(fx), j = Math.floor(fz), u = fx - i, v = fz - j;
  const a = g.h[j * g.nx + i], b = g.h[j * g.nx + i + 1], c = g.h[(j + 1) * g.nx + i], d = g.h[(j + 1) * g.nx + i + 1];
  return (a * (1 - u) + b * u) * (1 - v) + (c * (1 - u) + d * u) * v;
}
// Uint16 decimetres above the base, each row delta-coded (mod 65536) so gzip finds the pattern.
function deltaU16(g) {
  const out = new Uint16Array(g.nx * g.nz);
  for (let j = 0; j < g.nz; j++) {
    let prev = 0;
    for (let i = 0; i < g.nx; i++) {
      const q = Math.max(0, Math.min(65535, Math.round((g.h[j * g.nx + i] - g.base) * 10)));
      out[j * g.nx + i] = (q - prev) & 0xffff; prev = q;
    }
  }
  return out;
}
function pad4(parts) {
  const len = parts.reduce((a, p) => a + p.length, 0);
  if (len % 4) parts.push(Buffer.alloc(4 - (len % 4)));
}
// Nearest-sample lookup (bucketed) for tagging barriers.
function segIndex(S) {
  const C = 40, map = new Map();
  S.forEach((p, i) => { const k = `${Math.floor(p.x / C)},${Math.floor(p.z / C)}`; (map.get(k) || map.set(k, []).get(k)).push(i); });
  return (x, z) => {
    let best = -1, bd = 30 * 30;
    const cx = Math.floor(x / C), cz = Math.floor(z / C);
    for (let a = -1; a <= 1; a++) for (let b = -1; b <= 1; b++) for (const i of map.get(`${cx + a},${cz + b}`) || []) {
      const d = (S[i].x - x) ** 2 + (S[i].z - z) ** 2; if (d < bd) { bd = d; best = i; }
    }
    return best;
  };
}
// Rings of a way or multipolygon relation (member ways stitched end to end).
function rings(el, toXZ) {
  if (el.type === 'way') return el.geometry ? [el.geometry.map((p) => toXZ(p.lat, p.lon))] : [];
  const segs = (el.members || []).filter((m) => m.type === 'way' && m.geometry).map((m) => m.geometry.map((p) => toXZ(p.lat, p.lon)));
  const out = [];
  const same = (a, b) => Math.abs(a[0] - b[0]) < 0.01 && Math.abs(a[1] - b[1]) < 0.01;
  while (segs.length) {
    let ring = segs.shift();
    for (let guard = 0; guard < 500 && !same(ring[0], ring.at(-1)); guard++) {
      const k = segs.findIndex((s) => same(s[0], ring.at(-1)) || same(s.at(-1), ring.at(-1)));
      if (k < 0) break;
      const s = segs.splice(k, 1)[0];
      ring = ring.concat(same(s[0], ring.at(-1)) ? s.slice(1) : s.slice().reverse().slice(1));
    }
    out.push(ring);
  }
  return out;
}
function treeMask(osm, near, toXZ) {
  const x0 = near.x0, z0 = near.z0;
  const nx = Math.ceil((near.nx * near.cell) / TREE_CELL), nz = Math.ceil((near.nz * near.cell) / TREE_CELL);
  const data = new Uint8Array(nx * nz);
  for (const el of osm.elements) {
    const rs = rings(el, toXZ).filter((r) => r.length > 3);
    if (!rs.length) continue;
    // Even-odd scanline fill over all of the element's rings (outers and holes together).
    for (let j = 0; j < nz; j++) {
      const z = z0 + (j + 0.5) * TREE_CELL, xs = [];
      for (const r of rs) for (let k = 0; k < r.length - 1; k++) {
        const [ax, az] = r[k], [bx, bz] = r[k + 1];
        if ((az <= z) !== (bz <= z)) xs.push(ax + ((z - az) / (bz - az)) * (bx - ax));
      }
      xs.sort((a, b) => a - b);
      for (let k = 0; k + 1 < xs.length; k += 2) {
        const i0 = Math.max(0, Math.ceil((xs[k] - x0) / TREE_CELL - 0.5)), i1 = Math.min(nx - 1, Math.floor((xs[k + 1] - x0) / TREE_CELL - 0.5));
        for (let i = i0; i <= i1; i++) data[j * nx + i] = 255;
      }
    }
  }
  let n = 0; for (const v of data) if (v) n++;
  return { x0, z0, nx, nz, data, cover: (100 * n) / data.length };
}
// Lakes: flat polygons at the DEM's lowest point along their shore, simplified to ≈4 m.
function lakeShapes(osm, toXZ, demAt, near) {
  const out = [];
  for (const el of osm.elements) {
    if (el.tags?.water && /river|stream|canal|ditch/.test(el.tags.water)) continue;
    for (const r of rings(el, toXZ)) {
      if (r.length < 4) continue;
      let area = 0; for (let k = 0; k < r.length - 1; k++) area += r[k][0] * r[k + 1][1] - r[k + 1][0] * r[k][1];
      if (Math.abs(area / 2) < 1500) continue;
      const inside = r.every(([x, z]) => x > near.x0 && z > near.z0 && x < near.x0 + (near.nx - 1) * near.cell && z < near.z0 + (near.nz - 1) * near.cell);
      if (!inside) continue;
      const simp = dp(r, 4);
      const hs = simp.map(([x, z]) => demAt(x, z)).sort((a, b) => a - b);
      out.push({ y: +hs[Math.floor(hs.length * 0.2)].toFixed(1), pts: simp.flat().map((v) => +v.toFixed(1)) });
    }
  }
  return out;
}
function dp(pts, eps) {
  if (pts.length < 3) return pts;
  let dmax = 0, idx = 0;
  const [ax, az] = pts[0], [bx, bz] = pts.at(-1), L = Math.hypot(bx - ax, bz - az) || 1;
  for (let i = 1; i < pts.length - 1; i++) {
    const d = Math.abs((bx - ax) * (az - pts[i][1]) - (ax - pts[i][0]) * (bz - az)) / L;
    if (d > dmax) { dmax = d; idx = i; }
  }
  if (dmax <= eps) return [pts[0], pts.at(-1)];
  return dp(pts.slice(0, idx + 1), eps).slice(0, -1).concat(dp(pts.slice(idx), eps));
}
// The skyline beyond the far grid: for each half degree of azimuth, the highest ground seen from
// the road's mean height between 17 and 90 km (zoom 8, ≈0.5 km/px), with the earth's curvature
// (and standard refraction, k = 0.13) dropping it. Stored as the height it would have on a ring
// 30 km out, so the same angle is drawn there.
async function panorama(ys, toLL) {
  let h0 = 0; for (const v of ys) h0 += v; h0 /= ys.length;
  const R = 30000, out = [];
  for (let k = 0; k < 720; k++) {
    const az = (k / 720) * 2 * Math.PI, sx = Math.sin(az), sz = -Math.cos(az);
    let best = -Infinity;
    for (let r = 17000; r <= 90000; r += 500) {
      const [la, lo] = toLL(sx * r, sz * r);
      const e = Math.max(0, await elevation(la, lo, 8));
      const drop = ((1 - 0.13) * r * r) / (2 * R_EARTH);
      best = Math.max(best, (e - drop - h0) / r);
    }
    out.push(Math.round(h0 + best * R));
  }
  return { r: R, az0: 0, y: out };
}

