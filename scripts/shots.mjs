// Dev: screenshots of key moments. node scripts/shots.mjs [outdir] [url]
import { chromium } from '@playwright/test';
const out = process.argv[2] || 'shots';
const url = process.argv[3] || 'http://localhost:4311/coldgas/';
const browser = await chromium.launch({ args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
const errors = [];
page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') errors.push(m.text()); });
page.on('pageerror', (e) => errors.push('PAGEERROR ' + e.message));
await page.goto(url);
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}/1-title.png` });
await page.evaluate(() => window.__coldgas.startRun('reveal'));
const wait = async (pred, ms = 30000) => { const t0 = Date.now(); while (Date.now() - t0 < ms) { if (await page.evaluate(pred)) return true; await page.waitForTimeout(50); } return false; };
await wait(() => window.__coldgas.S.mode === 'live');
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/2-runup.png` });
await wait(() => window.__coldgas.S.run?.phase === 'air');
await page.waitForTimeout(250);
await page.screenshot({ path: `${out}/3-lift.png` });
await wait(() => Math.abs(window.__coldgas.S.run?.t.rollAccum || 0) > 2.6);
await page.screenshot({ path: `${out}/4-roll.png` });
await wait(() => window.__coldgas.S.run?.phase === 'landed');
await page.waitForTimeout(150);
await page.screenshot({ path: `${out}/5-land.png` });
await wait(() => window.__coldgas.S.mode === 'results');
await page.waitForTimeout(3500);
await page.screenshot({ path: `${out}/6-results.png` });
console.log(JSON.stringify(await page.evaluate(() => ({ total: window.__coldgas.S.card?.total, verdict: window.__coldgas.S.card?.verdict }))));
console.log('errors:', errors.slice(0, 10).join('\n'));
await browser.close();
