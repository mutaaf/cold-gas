#!/usr/bin/env node
// The sim's golden traces for the native port (docs/NATIVE.md §3, 0146).
//   npm run vectors              write ios/Packages/ColdGasCore/Tests/Vectors/ (generated: never hand-edit)
//   node scripts/vectors.mjs --check   regenerate in memory; exit 1 naming each file that differs
// A sim or scorer change regenerates these in the same PR, or `npm run check` goes red.
import { mkdirSync, readFileSync, writeFileSync, existsSync, readdirSync, rmSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, dirname } from 'node:path';
import { initPhysics } from '../src/sim/engine.js';
import { SIM_VERSION } from '../src/sim/run.js';
import { buildVectors, VECTOR_DIR, VECTOR_FORMAT } from './vectors-lib.mjs';

await initPhysics();
const check = process.argv.includes('--check');
const t0 = performance.now();
const files = buildVectors();
const sha = (s) => createHash('sha256').update(s).digest('hex');
files['manifest.json'] = JSON.stringify({
  format: VECTOR_FORMAT, simVersion: SIM_VERSION,
  note: 'GENERATED by `npm run vectors` (scripts/vectors.mjs). Never edit by hand.',
  files: Object.keys(files).sort().map((p) => ({ path: p, sha256: sha(files[p]), bytes: Buffer.byteLength(files[p]) })),
}, null, 1) + '\n';

const onDisk = (dir, base = '') => !existsSync(dir) ? [] : readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
  e.isDirectory() ? onDisk(join(dir, e.name), base + e.name + '/') : [base + e.name]);

if (check) {
  const bad = [];
  for (const [p, text] of Object.entries(files)) {
    const f = join(VECTOR_DIR, p);
    if (!existsSync(f)) bad.push(`${p}: missing`);
    else if (readFileSync(f, 'utf8') !== text) bad.push(`${p}: differs`);
  }
  for (const p of onDisk(VECTOR_DIR)) if (!(p in files)) bad.push(`${p}: not generated (stale file)`);
  if (bad.length) {
    console.error(`vectors: ${bad.length} file(s) out of date. Run \`npm run vectors\` and commit the result (docs/NATIVE.md §3).\n  ` + bad.join('\n  '));
    process.exit(1);
  }
  console.log(`vectors: ${Object.keys(files).length} files current (SIM_VERSION ${SIM_VERSION}, ${((performance.now() - t0) / 1000).toFixed(1)} s)`);
} else {
  rmSync(join(VECTOR_DIR, 'runs'), { recursive: true, force: true });
  rmSync(join(VECTOR_DIR, 'haptics'), { recursive: true, force: true });
  rmSync(join(VECTOR_DIR, 'input'), { recursive: true, force: true });
  let bytes = 0;
  for (const [p, text] of Object.entries(files)) {
    const f = join(VECTOR_DIR, p);
    mkdirSync(dirname(f), { recursive: true });
    writeFileSync(f, text);
    bytes += Buffer.byteLength(text);
  }
  console.log(`vectors: wrote ${Object.keys(files).length} files, ${(bytes / 1e6).toFixed(2)} MB, to ${VECTOR_DIR} (${((performance.now() - t0) / 1000).toFixed(1)} s)`);
}
