// Re-bundle Rapier's JS API (@dimforge/rapier3d-deterministic, Apache-2.0) into one ES module the
// game, the Worker, Vitest and plain Node can all import: src/vendor/rapier3d.js.
//
// The package ships wasm-bindgen's "bundler" glue (`import * as wasm from "./x.wasm"`, extensionless
// relative imports). That form only loads under a bundler with ESM-wasm integration, and the
// Cloudflare Worker can't compile WebAssembly from bytes at runtime. So the bundle drops the wasm
// import and exports the glue (`__bg`) instead; src/sim/engine.js instantiates the .wasm the way
// each host can (fetch in the browser, a precompiled module in the Worker, the file in Node) and
// hands the instance to the glue. The WASM binary itself is used untouched from node_modules.
//
//   node scripts/vendor-rapier.mjs        (after bumping the package)
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname } from 'node:path';

const require = createRequire(import.meta.url);
const pkgJson = require.resolve('@dimforge/rapier3d-deterministic/package.json');
const pkgDir = dirname(pkgJson);
const { version, license } = JSON.parse(readFileSync(pkgJson, 'utf8'));
const out = new URL('../src/vendor/rapier3d.js', import.meta.url).pathname;

await build({
  stdin: {
    contents: `export * from '@dimforge/rapier3d-deterministic/exports.js';\nexport * as __bg from '@dimforge/rapier3d-deterministic/rapier_wasm3d_bg.js';\n`,
    resolveDir: pkgDir, loader: 'js',
  },
  bundle: true, format: 'esm', minify: true, legalComments: 'none', target: 'es2022', outfile: out,
  plugins: [{
    name: 'no-wasm-import',
    setup(b) {
      b.onLoad({ filter: /rapier_wasm3d\.js$/ }, () => ({ contents: 'export * from "./rapier_wasm3d_bg.js";', loader: 'js', resolveDir: pkgDir }));
    },
  }],
});
const body = readFileSync(out, 'utf8');
writeFileSync(out, `/* Rapier ${version} (@dimforge/rapier3d-deterministic), ${license}, (c) Dimforge EURL and contributors.
   https://github.com/dimforge/rapier. Generated by scripts/vendor-rapier.mjs: do not edit. The WASM
   binary is loaded from node_modules by src/sim/engine.js. Licence: src/vendor/RAPIER-LICENSE. */
${body}`);
writeFileSync(new URL('../src/vendor/RAPIER-LICENSE', import.meta.url), readFileSync(`${pkgDir}/LICENSE`));
console.log('wrote', out, (body.length / 1024).toFixed(0), 'KiB, rapier', version);
