// THE ENDLESS ROAD: a procedurally generated world for Free Drive, deterministic from its seed.
// Pure like the rest of src/sim (+, −, ×, ÷, √, floor and integer hashing; dmath for angles), so
// a seed builds the same land and the same road, bit for bit, in the page, in its terrain worker
// and in Node. Nothing here knows about three.js.
//
//   terrain   four biomes blended by low-frequency fields: mountain passes (ridged noise, rock
//             and snow), coast (the land falls into the sea), desert (mesas and dunes) and forest
//             (rolling hills). heightAt() gives the height and its exact gradient.
//   road      one road, generated 3 m at a time from s = 0 northward (+z), forever. It winds on
//             noise, steers along the contours (toward the side whose ground is nearer its own
//             height), keeps clear of itself and of the sea, holds a design grade with smooth
//             vertical curves, banks into its curves, widens through tight ones, and puts in
//             bridges over valleys and the sea and guard rails above drops. Its heading never
//             turns more than ±72° off north, so z only ever grows along it: everything that can
//             touch a point at z is generated by the time the road reaches z + reach. That makes
//             the ground a pure function of (seed, x, z) wherever it's asked for.
//   surface   the road object has the same shape as a baked one (src/sim/roads.js), so the same
//             roadSurface() drives it: ribbon, graded 1:4 roadside, structural slopes, rails.
//
// The sim calls `ensure(z)` (the course's sdf does it for every query) and gets segments
// published up to z + reach; a published sample never changes again.
import { MATERIALS } from './courses.js';
import { roadSurface, cellKey, SHOULDER } from './roads.js';
import { dsin, dcos } from './dmath.js';
import { seedOf, fbm, ridged, smooth, vnoise1, hash2 } from './noise.js';

export const ENDLESS_VERSION = 1;          // bump when a seed would build a different world
export const SPACING = 3;                  // m between road samples
export const BIOMES = [
  { id: 'mountain', name: 'Mountain pass' },
  { id: 'coast', name: 'Coast road' },
  { id: 'desert', name: 'Desert' },
  { id: 'forest', name: 'Forest' },
];
const MAX_HEADING = 1.25;                  // rad off north (≈72°): z grows along the road
const CELL = 32;                           // the segment map's cells (m)
const EXACT = 36;                          // m past the shoulder the earthwork still shapes the ground
const SEA = 0;                             // sea level (m)

// ---- Terrain ---------------------------------------------------------------------------------
// The land is laid out along a macro path, x = xm(z): a long, slow meander northward that the road
// wanders around (within a few hundred metres). Biomes come in bands along z, a few kilometres
// each, so a drive north passes through all of them; on the coast the sea lies to one side of the
// macro path, beyond a shoreline 250–450 m out, the way a coast road runs with the sea beside it.
const fA = [0, 0, 0], fB = [0, 0, 0], fC = [0, 0, 0], sm = [0, 0], t3 = [0, 0, 0], t3b = [0, 0, 0], n1 = [0, 0];

// 1D fractal noise along z (two octaves), [v, dv/dz].
function fbm1(seed, z, wl, out) {
  vnoise1(seed, z / wl, n1);
  let v = n1[0], d = n1[1] / wl;
  vnoise1(seed ^ 0x9e37, (z * 2.03) / wl + 7.1, n1);
  v += 0.5 * n1[0]; d += (0.5 * n1[1] * 2.03) / wl;
  out[0] = v / 1.5; out[1] = d / 1.5;
  return out;
}
const mp = [0, 0];
// The macro path's x at z, and dx/dz.
export function macroX(seed, z, out = mp) {
  fbm1(seed ^ 0x3a7, z, 16000, out);
  out[0] *= 3200; out[1] *= 3200;
  return out;
}
const sideOf = (seed, z) => (hash2(seed ^ 0x51de, Math.floor(z / 40000), 0) < 0.5 ? -1 : 1);

// The biome weights at (x, z) into w[0..3] (mountain, coast, desert, forest; they sum to 1) and
// their gradients into gx, gz.
export function biomeWeights(seed, x, z, w, gx, gz) {
  fbm1(seed ^ 0xa11ce, z, 11000, n1); fA[0] = n1[0]; fA[1] = 0; fA[2] = n1[1];
  fbm(seed ^ 0xb0b, x * 0.25, z, 6000, 2, 0.5, fB); fB[1] *= 0.25;
  fbm(seed ^ 0xc0de, x * 0.25, z, 5200, 2, 0.5, fC); fC[1] *= 0.25;
  smooth(0.28, 0.52, fA[0], sm); const c = sm[0], cx = 0, cz = sm[1] * fA[2];
  smooth(-0.06, 0.24, fC[0], sm); const m = sm[0], mx = sm[1] * fC[1], mz = sm[1] * fC[2];
  smooth(0.0, 0.2, fB[0], sm); const d = sm[0], dX = sm[1] * fB[1], dZ = sm[1] * fB[2];
  const nc = 1 - c, nm = 1 - m, nd = 1 - d;
  w[0] = m * nc; gx[0] = mx * nc - m * cx; gz[0] = mz * nc - m * cz;
  w[1] = c; gx[1] = cx; gz[1] = cz;
  w[2] = nc * nm * d; gx[2] = -cx * nm * d - nc * mx * d + nc * nm * dX; gz[2] = -cz * nm * d - nc * mz * d + nc * nm * dZ;
  w[3] = nc * nm * nd; gx[3] = -cx * nm * nd - nc * mx * nd - nc * nm * dX; gz[3] = -cz * nm * nd - nc * mz * nd - nc * nm * dZ;
  return w;
}

// The valley the macro path runs along: its floor height V(z) (cols and basins), and how much of
// a biome's relief stands at (x, z): a quarter of it on the valley floor, all of it a kilometre
// out. That's what lets a road that can only head north still find its way through mountains: it
// follows the valley, and the peaks stand either side. Into vl: [V, dV/dz, grow, dgrow/dx,
// dgrow/dz, lateral offset from the path, d(lat)/dz].
const vl = [0, 0, 0, 0, 0, 0, 0];
function valley(seed, x, z, out = vl) {
  fbm1(seed ^ 0x7a11e7, z, 9000, n1);
  out[0] = 170 + 170 * n1[0]; out[1] = 170 * n1[1];
  macroX(seed, z, mp);
  const lat = x - mp[0], al = Math.sqrt(lat * lat + 400), dal = lat / al;      // a smooth |lat|
  smooth(120, 1000, al, sm);
  out[2] = 0.15 + 0.85 * sm[0];
  out[3] = 0.85 * sm[1] * dal; out[4] = -0.85 * sm[1] * dal * mp[1];
  out[5] = lat; out[6] = -mp[1];
  return out;
}

// Each biome's land, [h, dh/dx, dh/dz]. The shortest wavelengths are ≈ 100 m, so the 4 m mesh
// the renderer draws is the ground the car drives on to within a centimetre or two; finer relief
// is shading only.
function biomeHeight(seed, b, x, z, V, out) {
  const g = V[2], gx = V[3], gz = V[4];
  if (b === 0) {
    // Mountains: ridged ranges either side of the valley, 50 m of rolling relief on its floor.
    ridged(seed ^ 0x1001, x, z, 2600, 5, 0.5, t3);
    fbm(seed ^ 0x1002, x, z, 700, 3, 0.5, t3b);
    const R = 980 * t3[0];
    out[0] = V[0] + 60 + g * R + 50 * t3b[0];
    out[1] = gx * R + g * 980 * t3[1] + 50 * t3b[1];
    out[2] = V[1] + gz * R + g * 980 * t3[2] + 50 * t3b[2];
  } else if (b === 1) {
    // Land rising inland from a shoreline `shore` m out from the macro path, on the sea's side:
    // gently near the water, then hills; cliffs and coves from the noise.
    const side = sideOf(seed, z);
    fbm1(seed ^ 0x5407e, z, 2400, n1);
    const shore = 230 + 90 * n1[0], dShore = 90 * n1[1];
    const lat = V[5] * side, latx = side, latz = V[6] * side;
    const e = shore - lat, ex = -latx, ez = dShore - latz;          // m inland of the shoreline
    // Profile: steep coastal slopes from the water up to the valley's own height a few hundred
    // metres inland (a road on a shelf high above the sea), A·sat(e/L), smooth and C1.
    const A = 0.55 * V[0] + 45, L = 170, k = e / L, r = Math.sqrt(1 + k * k), sat = k / r, dsat = 1 / (r * r * r) / L;
    const base = A * sat + 0.03 * (e > 0 ? e : 0), dbase = A * dsat + (e > 0 ? 0.03 : 0);
    // Rolling headlands inland, gullies and cliffs at the water (more of both away from the road).
    fbm(seed ^ 0x1003, x, z, 700, 3, 0.5, t3b);
    ridged(seed ^ 0x1008, x, z, 1200, 3, 0.5, t3);
    const R = 60 * t3b[0] + 70 * t3[0], Rx = 60 * t3b[1] + 70 * t3[1], Rz = 60 * t3b[2] + 70 * t3[2];
    const gc = 0.35 + 0.65 * g, gcx = 0.65 * gx, gcz = 0.65 * gz;
    out[0] = base + gc * R - 12;
    out[1] = dbase * ex + gcx * R + gc * Rx;
    out[2] = dbase * ez + 0.55 * V[1] * sat + gcz * R + gc * Rz;
  } else if (b === 2) {
    // Desert: a high plain with mesas (flat-topped tables with steep sides) and dunes.
    fbm(seed ^ 0x1004, x, z, 3000, 3, 0.5, t3);
    fbm(seed ^ 0x1005, x, z, 1500, 3, 0.5, t3b);
    smooth(0.16, 0.3, t3b[0], sm);
    const R = 70 * t3[0] + 95 * sm[0], Rx = 70 * t3[1] + 95 * sm[1] * t3b[1], Rz = 70 * t3[2] + 95 * sm[1] * t3b[2];
    fbm(seed ^ 0x1006, x, z, 220, 2, 0.5, t3b);
    // The tables stand closer to the road than other biomes' relief does (a road through mesas).
    const gd = 0.4 + 0.6 * g, gdx = 0.6 * gx, gdz = 0.6 * gz;
    out[0] = V[0] + 40 + gd * R + 7 * t3b[0];
    out[1] = gdx * R + gd * Rx + 7 * t3b[1];
    out[2] = V[1] + gdz * R + gd * Rz + 7 * t3b[2];
  } else {
    // Forest: rolling hills.
    fbm(seed ^ 0x1007, x, z, 1800, 4, 0.5, t3);
    fbm(seed ^ 0x1009, x, z, 500, 2, 0.5, t3b);
    const R = 190 * t3[0];
    out[0] = V[0] + g * R + 22 * t3b[0];
    out[1] = gx * R + g * 190 * t3[1] + 22 * t3b[1];
    out[2] = V[1] + gz * R + g * 190 * t3[2] + 22 * t3b[2];
  }
  return out;
}

// The terrain of a seed: natural height with gradient, biome weights, and the ground's material.
export function createTerrain(seedIn) {
  const seed = seedOf(seedIn);
  const w = [0, 0, 0, 0], wx = [0, 0, 0, 0], wz = [0, 0, 0, 0], hb = [0, 0, 0];
  const last = { x: NaN, z: NaN, h: 0, w: [0, 0, 0, 0] };
  // Natural ground at (x, z): out = [h, dh/dx, dh/dz]. h = Σ wᵦ·Hᵦ, so ∇h = Σ (∇wᵦ·Hᵦ + wᵦ·∇Hᵦ).
  function heightAt(x, z, out) {
    biomeWeights(seed, x, z, w, wx, wz);
    valley(seed, x, z, vl);
    let h = 0, gx = 0, gz = 0;
    for (let b = 0; b < 4; b++) {
      if (w[b] < 1e-6 && wx[b] === 0 && wz[b] === 0) continue;
      biomeHeight(seed, b, x, z, vl, hb);
      h += w[b] * hb[0]; gx += wx[b] * hb[0] + w[b] * hb[1]; gz += wz[b] * hb[0] + w[b] * hb[2];
    }
    out[0] = h; out[1] = gx; out[2] = gz;
    last.x = x; last.z = z; last.h = h;
    for (let b = 0; b < 4; b++) last.w[b] = w[b];
    return out;
  }
  const wtmp = [0, 0, 0, 0], gtmp = [0, 0, 0, 0], gtmp2 = [0, 0, 0, 0], htmp = [0, 0, 0];
  function weightsAt(x, z, out = wtmp) {
    if (x === last.x && z === last.z) { for (let b = 0; b < 4; b++) out[b] = last.w[b]; return out; }
    return biomeWeights(seed, x, z, out, gtmp, gtmp2);
  }
  // What a tyre meets off the road: sand on desert flats and at the shore, rock where it's steep.
  function matAt(x, z, ny) {
    if (ny < 0.8) return MATERIALS.rock;
    const wv = weightsAt(x, z);
    const h = x === last.x && z === last.z ? last.h : heightAt(x, z, htmp)[0];
    if (wv[2] > 0.5 && ny > 0.86) return MATERIALS.sand;
    if (wv[1] > 0.4 && h < SEA + 2.5) return MATERIALS.sand;
    return MATERIALS.grass;
  }
  // The dominant biome's index at (x, z).
  function biomeAt(x, z) {
    const wv = weightsAt(x, z);
    let best = 0;
    for (let b = 1; b < 4; b++) if (wv[b] > wv[best]) best = b;
    return best;
  }
  return { seed, heightAt, weightsAt, matAt, biomeAt, sea: SEA };
}

// ---- The road ----------------------------------------------------------------------------------
// Per-biome design: minimum curve radius (m), the wander's strength, maximum grade, half-width.
const DESIGN = [
  { rmin: 48, wander: 0.016, grade: 0.1, hw: 3.3 },      // mountain
  { rmin: 100, wander: 0.007, grade: 0.085, hw: 3.6 },    // coast
  { rmin: 160, wander: 0.004, grade: 0.07, hw: 3.7 },     // desert
  { rmin: 90, wander: 0.008, grade: 0.085, hw: 3.4 },     // forest
];

const GROW = ['x', 'z', 'y', 'hw', 'bank', 'vnx', 'vnz', 'sx', 'sz', 'dx', 'dz', 'len', 'grade'];

export function createEndlessRoad(seedIn) {
  const terrain = createTerrain(seedIn);
  const seed = terrain.seed;
  const reach = 4.4 + SHOULDER + EXACT + 8;
  const road = {
    endless: true, seed,
    meta: { id: 'endless', spacing: SPACING, marking: 'eu', coast: true, seed, version: ENDLESS_VERSION },
    n: 0, m: 0, length: 0, hwMax: 4.4, reach, exact: EXACT,
    flags: new Uint8Array(1024),
    grid: { cells: new Map(), cell: CELL },
    bounds: { minX: Infinity, maxX: -Infinity, minZ: Infinity, maxZ: -Infinity },
    zMax: -Infinity,                       // the published road's northmost point
    dem: terrain.heightAt, matAt: terrain.matAt, terrain,
    ensure, generate, poseHint: null,
  };
  for (const k of GROW) road[k] = new Float64Array(1024);
  road.biome = new Uint8Array(1024);

  // The generator's own samples (one ahead of what's published) and its state.
  const G = { x: [], z: [], y: [], hw: [], bank: [], flags: [], biome: [] };
  const st = { x: 0, z: 0, th: 0, k: 0, y: 0, g: 0, bridge: false, railL: 0, railR: 0, runL: 0, runR: 0 };
  const h3 = [0, 0, 0], n2 = [0, 0], wv = [0, 0, 0, 0];

  // Start on the macro path, or the first point beside it (±150 m steps) well above the sea.
  {
    const xm = macroX(seed, 0)[0];
    let x0 = xm;
    for (let k = 0; k < 40; k++) {
      const x = xm + (k % 2 ? 1 : -1) * Math.floor((k + 1) / 2) * 150;
      if (terrain.heightAt(x, 0, h3)[0] > 12) { x0 = x; break; }
    }
    st.x = x0; st.z = 0; st.th = 0; st.k = 0;
    st.y = Math.max(SEA + 4, aheadHeight(x0, 0, 0));
  }

  function aheadHeight(x, z, th) {
    // The ground the road should ride: a look-ahead average along the heading.
    // Near ground counts most; the far samples start a long descent or climb early (a road
    // eases into a valley rather than bridging it once it's there).
    const fx = dsin(th), fz = dcos(th);
    let s = 0, w = 0;
    for (let d = 0; d <= 240; d += 40) { const k = 1 / (1 + d / 60); s += k * terrain.heightAt(x + fx * d, z + fz * d, h3)[0]; w += k; }
    return s / w;
  }

  // Is any published segment (older than the last `skip`) within r of (x, z)? Returns the side
  // (+1: it's to the left of heading (fx, fz)) or 0.
  function nearOld(x, z, r, fx, fz, skip) {
    const c0 = Math.floor((x - r) / CELL), c1 = Math.floor((x + r) / CELL), d0 = Math.floor((z - r) / CELL), d1 = Math.floor((z + r) / CELL);
    let best = r * r, side = 0;
    for (let j = d0; j <= d1; j++) for (let i = c0; i <= c1; i++) {
      const list = road.grid.cells.get(cellKey(i, j));
      if (!list) continue;
      for (let k = 0; k < list.length; k++) {
        const s = list[k];
        if (s > road.m - skip) continue;
        const ex = road.x[s] - x, ez = road.z[s] - z, d2 = ex * ex + ez * ez;
        if (d2 < best) { best = d2; side = ex * fz - ez * fx > 0 ? 1 : -1; }     // left = (fz, −fx)
      }
    }
    return side;
  }

  // One more sample: steer, step 3 m, settle the height, decide the cross-section.
  function step() {
    const i = G.x.length;
    const sNow = i * SPACING;
    const b = terrain.biomeAt(st.x, st.z);
    terrain.weightsAt(st.x, st.z, wv);
    // Design values blended by biome weight.
    let rmin = 0, wander = 0, gmax = 0, hw0 = 0;
    for (let k = 0; k < 4; k++) { rmin += wv[k] * DESIGN[k].rmin; wander += wv[k] * DESIGN[k].wander; gmax += wv[k] * DESIGN[k].grade; hw0 += wv[k] * DESIGN[k].hw; }
    const kmax = 1 / rmin;
    const fx = dsin(st.th), fz = dcos(st.th), lx = fz, lz = -fx;
    // 1. Wander: slow noise along the road.
    vnoise1(seed ^ 0x77, sNow / 420, n2);
    let want = wander * n2[0] * 1.6;
    vnoise1(seed ^ 0x78, sNow / 140, n2);
    want += wander * n2[0] * 0.5;
    // 2. Contours: look 70 m ahead, left and right of the heading, and lean toward the side whose
    //    ground is nearer the road's height (that's how a pass winds up a mountainside).
    const L = 70, a = 0.38, ca = dcos(a), sa = dsin(a);
    const lfx = fx * ca + lx * sa, lfz = fz * ca + lz * sa, rfx = fx * ca - lx * sa, rfz = fz * ca - lz * sa;
    const hL = terrain.heightAt(st.x + lfx * L, st.z + lfz * L, h3)[0], hR = terrain.heightAt(st.x + rfx * L, st.z + rfz * L, h3)[0];
    const hC = terrain.heightAt(st.x + fx * L, st.z + fz * L, h3)[0];
    const dL = hL - st.y < 0 ? st.y - hL : hL - st.y, dR = hR - st.y < 0 ? st.y - hR : hR - st.y;
    let lean = (dR - dL) / 30;
    if (lean > 1) lean = 1; else if (lean < -1) lean = -1;
    const far = (st.x - macroX(seed, st.z, mp)[0]) / 320, fade = 1 / (1 + far * far * far * far);
    want += kmax * 0.55 * lean * fade;
    // 3. Keep out of the sea: if the ground ahead is near sea level, turn to the higher side.
    if (hC < SEA + 6 || hL < SEA + 3 || hR < SEA + 3) want += kmax * (hL > hR ? 0.9 : -0.9);
    // 4. Keep clear of itself.
    const side = nearOld(st.x + fx * 80, st.z + fz * 80, 95, fx, fz, 40);
    if (side) want -= side * kmax * 0.9;
    // 5. Stay within a few hundred metres of the macro path (where the land is laid out).
    // On the coast, hold a little inland of it (the sea lies on one side, a few hundred metres out).
    const off = st.x - macroX(seed, st.z, mp)[0] + sideOf(seed, st.z) * 30 * wv[1];
    let pull = off / 320;
    if (pull > 1) pull = 1; else if (pull < -1) pull = -1;
    // The heading is (sin θ, cos θ), so +θ swings toward +x: turn back by −off (gently near the
    // path, cubic), and lean toward the path's own direction (dx/dz).
    want += kmax * (0.15 * (mp[1] - dsin(st.th) / dcos(st.th)) - 0.7 * pull * pull * pull);
    // 6. Keep heading north: past ±0.8 rad, lean back hard (z must keep growing).
    if (st.th > 0.8) want -= ((st.th - 0.8) / (MAX_HEADING - 0.8)) * kmax * 1.2;
    else if (st.th < -0.8) want += ((-0.8 - st.th) / (MAX_HEADING - 0.8)) * kmax * 1.2;
    if (want > kmax) want = kmax; else if (want < -kmax) want = -kmax;
    // Curvature eases in and out (a spiral over ≈ 60 m into the tightest bend).
    const dk = kmax / 20;
    st.k += want - st.k > dk ? dk : want - st.k < -dk ? -dk : want - st.k;
    st.th += st.k * SPACING;
    if (st.th > MAX_HEADING) st.th = MAX_HEADING; else if (st.th < -MAX_HEADING) st.th = -MAX_HEADING;
    st.x += dsin(st.th) * SPACING; st.z += dcos(st.th) * SPACING;
    // Elevation: aim at the ground ahead, within the design grade, through smooth vertical curves.
    let target = aheadHeight(st.x, st.z, st.th);
    if (target < SEA + 4) target = SEA + 4;
    let gd = (target - st.y) / 70;
    if (gd > gmax) gd = gmax; else if (gd < -gmax) gd = -gmax;
    const dg = 0.0045;
    st.g += gd - st.g > dg ? dg : gd - st.g < -dg ? -dg : gd - st.g;
    st.y += st.g * SPACING;
    if (st.y < SEA + 3) { st.y = SEA + 3; if (st.g < 0) st.g = 0; }
    // Cross-section: wider through tight bends, banked into them (+ = left edge higher).
    const ak = st.k < 0 ? -st.k : st.k;
    const hw = hw0 + (ak * 30 > 0.7 ? 0.7 : ak * 30);
    let bank = -st.k * 9;
    if (bank > 0.06) bank = 0.06; else if (bank < -0.06) bank = -0.06;
    // Structures: a bridge where the road is well above the ground or over water (hysteresis),
    // steel guard rails where the ground falls away beside it, parapets on bridges.
    const hN = terrain.heightAt(st.x, st.z, h3)[0];
    const fill = st.y - hN;
    // (An embankment up to ≈ 16 m is cheaper than a viaduct; past that, a bridge.)
    if (!st.bridge && (fill > 16 || hN < SEA + 0.5)) st.bridge = true;
    else if (st.bridge && fill < 10 && hN > SEA + 1.5) st.bridge = false;
    const nlx = dcos(st.th), nlz = -dsin(st.th);
    const hSideL = terrain.heightAt(st.x + nlx * (hw + 7), st.z + nlz * (hw + 7), h3)[0];
    const hSideR = terrain.heightAt(st.x - nlx * (hw + 7), st.z - nlz * (hw + 7), h3)[0];
    const dropL = st.y - hSideL, dropR = st.y - hSideR;
    // Rails come on at a 4 m drop and stay on for at least 30 m (no flicker).
    st.runL = dropL > 4 ? 10 : st.runL > 0 ? st.runL - 1 : 0;
    st.runR = dropR > 4 ? 10 : st.runR > 0 ? st.runR - 1 : 0;
    let flags = st.bridge ? 1 : 0;
    if (st.bridge) flags |= (2 << 2) | (2 << 4);
    else { if (st.runL > 0) flags |= 1 << 2; if (st.runR > 0) flags |= 1 << 4; }
    G.x.push(st.x); G.z.push(st.z); G.y.push(st.y); G.hw.push(hw); G.bank.push(bank); G.flags.push(flags); G.biome.push(b);
  }

  function grow(need) {
    if (road.x.length >= need) return;
    let cap = road.x.length;
    while (cap < need) cap *= 2;
    for (const k of GROW) { const a = new Float64Array(cap); a.set(road[k]); road[k] = a; }
    const b = new Uint8Array(cap); b.set(road.biome); road.biome = b;
    const f = new Uint8Array(cap); f.set(road.flags); road.flags = f;
  }

  // Publish generated sample i (needs sample i + 1 for its segment and vertex normal).
  function publish() {
    const i = road.n;
    grow(i + 2);
    road.x[i] = G.x[i]; road.z[i] = G.z[i]; road.y[i] = G.y[i]; road.hw[i] = G.hw[i]; road.bank[i] = G.bank[i];
    road.flags[i] = G.flags[i]; road.biome[i] = G.biome[i];
    // Segment i: from sample i to i + 1 (generated, not yet published).
    const ex = G.x[i + 1] - G.x[i], ez = G.z[i + 1] - G.z[i], Ls = Math.sqrt(ex * ex + ez * ez) || 1e-6;
    road.sx[i] = G.x[i]; road.sz[i] = G.z[i]; road.dx[i] = ex / Ls; road.dz[i] = ez / Ls; road.len[i] = Ls;
    road.grade[i] = (G.y[i + 1] - G.y[i]) / Ls;
    // Vertex normal i: the bisector of segments i − 1 and i.
    const a = i > 0 ? i - 1 : i;
    let nx = road.dz[a] + road.dz[i], nz = -road.dx[a] - road.dx[i];
    const nl = Math.sqrt(nx * nx + nz * nz) || 1;
    road.vnx[i] = nx / nl; road.vnz[i] = nz / nl;
    road.n = i + 1;
    // Segment i − 1 is now complete (both vertex normals final): it joins the map.
    if (i > 0) {
      const s = i - 1;
      road.m = i;
      const r = reach;
      const ax = Math.min(road.x[s], road.x[s + 1]) - r, bx = Math.max(road.x[s], road.x[s + 1]) + r;
      const az = Math.min(road.z[s], road.z[s + 1]) - r, bz = Math.max(road.z[s], road.z[s + 1]) + r;
      for (let cj = Math.floor(az / CELL); cj <= Math.floor(bz / CELL); cj++)
        for (let ci = Math.floor(ax / CELL); ci <= Math.floor(bx / CELL); ci++) {
          const key = cellKey(ci, cj);
          let list = road.grid.cells.get(key);
          if (!list) { list = []; road.grid.cells.set(key, list); }
          list.push(s);
        }
    }
    road.length = road.m * SPACING;
    const B = road.bounds;
    if (road.x[i] < B.minX) B.minX = road.x[i]; if (road.x[i] > B.maxX) B.maxX = road.x[i];
    if (road.z[i] < B.minZ) B.minZ = road.z[i]; if (road.z[i] > B.maxZ) B.maxZ = road.z[i];
    if (road.m > 0) road.zMax = road.z[road.m];
  }

  // Generate and publish until the road reaches sample count n (or more).
  function generate(n) {
    while (road.n < n) {
      while (G.x.length < road.n + 2) step();
      publish();
    }
    return road;
  }
  // Everything that can shape the ground at z: the road published past z + reach.
  function ensure(z) {
    const want = z + reach + 40;
    while (road.zMax < want) generate(road.n + 64);
    return road;
  }
  // The first 64 samples, so the road has a start.
  generate(64);
  return road;
}

// The biome a road sample runs through, by name.
export const biomeName = (road, i) => BIOMES[road.biome[Math.max(0, Math.min(road.n - 1, i))]].name;

// ---- The course ----------------------------------------------------------------------------------
// The endless road as a course the car drives (src/sim/courses.js defers to `course.sdf`). Objects
// placed in the world (src/sim/objects.js) are solids too: their colliders join the query here,
// behind this one function, so a different physics engine only has to swap what's behind it.
export function createEndlessCourse(seed, { objects = null, name = 'Endless' } = {}) {
  const road = createEndlessRoad(seed);
  const tmp = { x: 0, y: 0, z: 0, mat: null, obstacle: false, body: null };
  const course = {
    id: `endless:${road.seed}`, name, road, boxes: [], objects,
    start: { x: road.x[0], z: road.z[0] },
    runout: { zMin: -Infinity, zMax: Infinity },
    sdf(x, y, z, out) {
      if (z + road.reach + 40 > road.zMax) road.ensure(z);
      let phi = roadSurface(road, x, y, z, out);
      const objs = course.objects;
      if (objs && objs.count) {
        const d = objs.sdf(x, y, z, tmp, phi);
        if (d < phi) { phi = d; out.x = tmp.x; out.y = tmp.y; out.z = tmp.z; out.mat = tmp.mat; out.obstacle = tmp.obstacle; out.body = null; out.object = tmp.object; return phi; }
      }
      out.object = null;
      return phi;
    },
  };
  return course;
}
